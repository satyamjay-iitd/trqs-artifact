#!/usr/bin/env python3
"""Generate `tables/workload.tex` from `queries.py`.

The workload table is generated rather than hand-maintained because hand
maintenance is what put un-parseable DSL in the current one: its Q4 and Q5 print
`|a.cx-b.cx|>45`, which the parser rejects twice over -- absolute-value bars, and
two variables on one side of a bbox expression. Nothing in this file can print a
query the suite does not actually run, because the string it prints is the string
`run_suite.py` executes.

    ./gen_workload_tex.py                 # summary table -> ../tables/workload.tex
    ./gen_workload_tex.py --listing       # full DSL listing -> ../tables/workload-full.tex

24 rows of DSL do not fit one `table*`, so the summary carries ID / dataset /
objects / operators / description and the listing carries the DSL.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from queries import SUITE  # noqa: E402
from run_suite import targets  # noqa: E402

TABLES = Path(__file__).resolve().parent.parent / "tables"

DATASET_LABEL = {
    "soccernet": "SoccerNet",
    "i24_motion": "I-24 MOTION",
    "clevrer_merged": "CLEVRER",
    "nuscenes": "nuScenes",
}


def tex_escape(s: str) -> str:
    for a, b in (("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"),
                 ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"),
                 ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")):
        s = s.replace(a, b)
    return s


def verb(s: str) -> str:
    """DSL in a `\\texttt`, with the characters LaTeX would otherwise eat."""
    s = tex_escape(s)
    return s.replace("<", r"{\textless}").replace(">", r"{\textgreater}")


def summary() -> str:
    rows = []
    for q in SUITE:
        rows.append(
            f"    {tex_escape(q.id)} & {DATASET_LABEL[q.dataset]} & {q.objects} & "
            f"{', '.join(tex_escape(o) for o in q.ops)} & {tex_escape(q.desc)} \\\\"
        )
    return (
        "%!TEX root=../main.tex\n"
        "% GENERATED by suite/gen_workload_tex.py -- edit queries.py, not this file.\n"
        "\\begin{table*}\n"
        "  \\caption{Query workload. Every query is run on every sub-dataset of its\n"
        "  family; the DSL is listed in Table~\\ref{tab:workload-dsl}.}"
        "\\label{tab:workload-summary}\n"
        "  \\vspace{-10pt}\n  \\centering\n  \\small\n"
        "  \\begin{tabular}{llcp{4.2cm}p{7.5cm}}\n"
        "    \\toprule\n"
        "    ID & Dataset & \\#Obj & Operators & Description \\\\\n"
        "    \\midrule\n" + "\n".join(rows) + "\n"
        "    \\bottomrule\n  \\end{tabular}\n  \\vspace{-10pt}\n\\end{table*}\n"
    )


def listing() -> str:
    rows = []
    for q in SUITE:
        subs = targets(q, 1)
        dsl = q.dsl_for(subs[0]) if subs else str(q.dsl)
        note = ""
        if not isinstance(q.dsl, str):
            note = (f" \\emph{{(regions generated per scene; shown for "
                    f"{tex_escape(subs[0])})}}" if subs else "")
        rows.append(f"    {tex_escape(q.id)} & \\texttt{{{verb(dsl)}}}{note} \\\\[2pt]")
    return (
        "%!TEX root=../main.tex\n"
        "% GENERATED by suite/gen_workload_tex.py -- edit queries.py, not this file.\n"
        "\\begin{table*}\n"
        "  \\caption{Query workload, \\sys\\ DSL.}\\label{tab:workload-dsl}\n"
        "  \\vspace{-10pt}\n  \\centering\n  \\scriptsize\n"
        "  \\begin{tabular}{lp{15.5cm}}\n"
        "    \\toprule\n    ID & \\sys\\ DSL \\\\\n    \\midrule\n"
        + "\n".join(rows) + "\n"
        "    \\bottomrule\n  \\end{tabular}\n  \\vspace{-10pt}\n\\end{table*}\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--listing", action="store_true")
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    text = listing() if args.listing else summary()
    out = args.out or (TABLES / ("workload-full.tex" if args.listing else "workload.tex"))
    out.write_text(text)
    print(f"wrote {out} ({len(SUITE)} queries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
